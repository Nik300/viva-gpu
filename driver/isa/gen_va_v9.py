#!/usr/bin/env python3
# Generates the Valhall v9 (Mali-G57) instruction encoder tables of the direct AIR -> ISA compiler from Arm's ISA
# description (mesa/src/src/panfrost/compiler/kraid/isa-v9-v14.xml, Copyright Arm Ltd, MIT).
#
#   gen_va_v9.py ISA.xml OUT_DIR        -> OUT_DIR/va_v9_gen.h, OUT_DIR/va_v9_gen.c
#
# Every instruction (and alias) valid for arch 9 becomes an opcode VA_<NAME>[_<VARIANT>]; every field, virtual
# field and syntax operand name becomes a field id VAF_<name>; every enum value a constant VA_<ENUM>_<VALUE>.
# va_encode (va_encode.c) fills fixed ("exact") fields, caller-set fields, computed fields (the XML's expressions,
# compiled to C here) and defaults, and rejects missing or out-of-range ones.
import sys, re
import xml.etree.ElementTree as ET

ARCH = 9

def ok(e):
    return int(e.get('since')) <= ARCH <= int(e.get('until'))

def ident(s):
    return re.sub(r'[^A-Za-z0-9_]', '_', s)

def main(xml, out):
    root = ET.parse(xml).getroot()
    enums = {}
    for e in root.findall('enum'):
        if not ok(e):
            continue
        enums[e.get('name')] = [(v.get('name'), int(v.get('value'), 0)) for v in e.findall('value')]
    insts = [i for i in root.findall('instruction') if ok(i)]

    fields = {}
    def fid(n):
        if n not in fields:
            fields[n] = len(fields)
        return fields[n]
    for n in ('flow', 'fau_page_index'):
        fid(n)
    for i in insts:
        for f in i:
            if f.tag in ('field', 'virtual') and f.get('name'):
                fid(f.get('name'))
        for s in i.find('syntax').iter():
            if s.get('name'):
                fid(s.get('name'))

    def enum_value(etype, name):
        for n, v in enums[etype]:
            if n == name:
                return v
        raise KeyError(f'{etype}.{name}')

    def lit(e, ftype=None):
        t = e.get('enum') or e.get('type')
        v = e.get('literal')
        if t in enums:
            return str(enum_value(t, v))
        if ftype in enums and not re.match(r'^-?\d', v):
            return str(enum_value(ftype, v))
        return str(int(v, 0))

    def expr(e, ftype):
        if e.get('literal') is not None:
            return lit(e, ftype)
        if e.get('identifier') is not None:
            return f'V({fid(e.get("identifier"))})'
        op = e.get('operator')
        a = [expr(c, ftype) for c in e.findall('expression')]
        bin = {'add': '+', 'sub': '-', 'rshift': '>>', 'lshift': '<<', 'bitwise_and': '&', 'bitwise_or': '|',
               'bitwise_xor': '^', 'equal': '==', 'less_than': '<'}
        if op in bin:
            out_ = a[0]
            for x in a[1:]:
                out_ = f'({out_} {bin[op]} {x})'
            return out_
        if op == 'if':
            # if(c0, v0, c1, v1, ..., else)
            s = a[-1]
            for k in range(len(a) - 3, -1, -2):
                s = f'({a[k]} ? {a[k + 1]} : {s})'
            return s
        if op == 'inside':
            return f'({a[0]} >= {a[1]} && {a[0]} <= {a[2]})'
        if op == 'countones':
            return f'(int64_t)__builtin_popcountll((uint64_t){a[0]})'
        raise ValueError(op)

    KIND = {'SourceEncoding': 'VA_K_SRC', 'SourceEncoding64': 'VA_K_SRC64', 'int': 'VA_K_INT',
            'pc_rel_label_signed': 'VA_K_INT', 'float': 'VA_K_UINT'}

    h = []
    c = []
    h.append('// Generated by gen_va_v9.py from Arm\'s isa-v9-v14.xml (arch 9). Do not edit.')
    h.append('#pragma once')
    h.append('#include <stddef.h>'); h.append('#include <stdint.h>')
    h.append('enum va_op {')
    names = []
    for i in insts:
        n = 'VA_' + ident(i.get('name')) + ('_' + ident(i.get('variant')).upper() if i.get('variant') else '')
        names.append(n)
        h.append(f'    {n},')
    h.append('    VA_OP_COUNT')
    h.append('};')
    h.append('enum va_field {')
    for n, k in fields.items():
        h.append(f'    VAF_{ident(n)} = {k},')
    h.append(f'    VAF_COUNT = {len(fields)}')
    h.append('};')
    for en, vals in sorted(enums.items()):
        p = 'VA_' + ident(en).upper()
        for n, v in vals:
            h.append(f'#define {p}_{ident(n).upper()} {v}')
    h.append('enum va_kind { VA_K_UINT, VA_K_INT, VA_K_SRC, VA_K_SRC64, VA_K_ENUM, VA_K_ZERO, VA_K_IGNORE };')
    h.append('enum va_unit { VA_UNIT_FMA, VA_UNIT_CVT, VA_UNIT_SFU, VA_UNIT_MSG, VA_UNIT_NONE };')
    h.append('struct va_field_info { uint16_t field; uint8_t pos, width, kind, shift, align; uint8_t has_exact, has_default, computed; int64_t exact, def; };')
    h.append('struct va_op_info { const char *name, *variant; uint8_t unit; uint8_t nsrc; uint8_t has_dest, sr_read, sr_write;')
    h.append('    uint16_t nfields; const struct va_field_info *fields; int64_t (*compute)(unsigned field, const int64_t *v); };')
    h.append('extern const struct va_op_info va_op_info[VA_OP_COUNT];')
    h.append('extern const char *const va_field_name[VAF_COUNT];')

    c.append('// Generated by gen_va_v9.py from Arm\'s isa-v9-v14.xml (arch 9). Do not edit.')
    c.append('#include "va_v9_gen.h"')
    c.append('#define V(f) v[f]')
    infos = []
    for idx, i in enumerate(insts):
        n = names[idx]
        fl = []
        comp = []
        for f in i:
            if f.tag not in ('field', 'reserved'):
                continue
            pos, width = int(f.get('pos')), int(f.get('width'))
            if f.tag == 'reserved':
                k = 'VA_K_ZERO' if f.get('type') == 'zero' else 'VA_K_IGNORE'
                fl.append(f'{{ VAF_COUNT, {pos}, {width}, {k}, 0, 0, 1, 0, 0, 0, 0 }}')
                continue
            name = f.get('name')
            ftype = f.get('type')
            kind = KIND.get(ftype, 'VA_K_ENUM' if ftype in enums else 'VA_K_UINT')
            shift = align = 0
            m = f.get('modifier') or ''
            mm = re.match(r'shr\((\d+)\)', m)
            if mm:
                shift = int(mm.group(1))
            mm = re.match(r'align\((\d+)\)', m)
            if mm:
                align = int(mm.group(1))
            has_exact = has_def = computed = 0
            exact = dflt = 0
            if f.get('exact') is not None:
                has_exact = 1
                x = f.get('exact')
                exact = enum_value(ftype, x) if ftype in enums else int(x, 0)
            if f.get('default') is not None:
                has_def = 1
                x = f.get('default')
                dflt = enum_value(ftype, x) if ftype in enums else int(x, 0)
            ex = f.find('expression')
            if ex is not None:
                computed = 1
                comp.append((fid(name), expr(ex, ftype)))
            fl.append(f'{{ VAF_{ident(name)}, {pos}, {width}, {kind}, {shift}, {align}, {has_exact}, {has_def}, {computed}, {exact}, {dflt} }}')
        c.append(f'static const struct va_field_info f_{n}[] = {{ {", ".join(fl)} }};')
        cf = 'NULL'
        if comp:
            cf = f'c_{n}'
            c.append(f'static int64_t {cf}(unsigned field, const int64_t *v) {{')
            c.append('    switch (field) {')
            for k, e in comp:
                c.append(f'    case {k}: return {e};')
            c.append('    default: return 0;')
            c.append('    }')
            c.append('}')
        syn = i.find('syntax')
        nsrc = len(syn.findall('src'))
        has_dest = 1 if syn.find('dest') is not None else 0
        sr_read = 1 if any(s.get('direction') == 'input' for s in syn.findall('staging')) else 0
        sr_write = 1 if any(s.get('direction') == 'output' for s in syn.findall('staging')) else 0
        unit = {'fma': 'VA_UNIT_FMA', 'cvt': 'VA_UNIT_CVT', 'sfu': 'VA_UNIT_SFU', 'msg': 'VA_UNIT_MSG'}.get(i.get('exec_unit'), 'VA_UNIT_NONE')
        var = f'"{i.get("variant")}"' if i.get('variant') else 'NULL'
        infos.append(f'    [{n}] = {{ "{i.get("name")}", {var}, {unit}, {nsrc}, {has_dest}, {sr_read}, {sr_write}, '
                     f'sizeof f_{n} / sizeof f_{n}[0], f_{n}, {cf} }},')
    c.append('const struct va_op_info va_op_info[VA_OP_COUNT] = {')
    c += infos
    c.append('};')
    c.append('const char *const va_field_name[VAF_COUNT] = {')
    for n, k in fields.items():
        c.append(f'    [{k}] = "{n}",')
    c.append('};')
    open(f'{out}/va_v9_gen.h', 'w').write('\n'.join(h) + '\n')
    open(f'{out}/va_v9_gen.c', 'w').write('\n'.join(c) + '\n')

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
