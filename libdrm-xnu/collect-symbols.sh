#!/usr/bin/env bash
# Regenerate SYMBOLS.txt: undefined drm* symbols referenced by the Mesa
# static libraries in ../mesa/build-macos (run after ../mesa/build.sh).
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
B="$HERE/../mesa/build-macos"
LIBS="$("$HERE/../mesa/build.sh" fn mesa_libs | grep '\.a$')"
{
  echo "# libdrm symbols referenced by Mesa (mesa-26.2.6, llvmpipe+panfrost, macOS build)"
  echo "# Generated by collect-symbols.sh from 'nm -u' on build-macos static libs."
  echo "# Format: symbol <TAB> referencing objects"
  echo
  for l in $LIBS; do nm -A -u "$B/$l" 2>/dev/null | grep -E ' _drm[A-Za-z]' || true; done |
    sed -E 's|^.*/([^/]+\.a)\[?:?([^]:]+)\]?: *_(drm[A-Za-z0-9_]+)$|\3\t\1:\2|' |
    sort -u |
    awk -F'\t' '{a[$1]=a[$1] (a[$1]?", ":"") $2} END {for (k in a) print k "\t" a[k]}' | sort
} > "$HERE/SYMBOLS.txt"
echo "wrote $HERE/SYMBOLS.txt ($(grep -c '^drm' "$HERE/SYMBOLS.txt") symbols)"
